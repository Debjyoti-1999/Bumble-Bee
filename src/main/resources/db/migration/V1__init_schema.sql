-- Initial schema. Written for H2 / PostgreSQL; adjust identity columns for MySQL.

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(254)                NOT NULL,
    password_hash       VARCHAR(100)                NOT NULL,
    name                VARCHAR(100)                NOT NULL,
    date_of_birth       DATE                        NOT NULL,
    gender              VARCHAR(20)                 NOT NULL,
    bio                 VARCHAR(1000),
    profile_picture_url VARCHAR(2048),
    latitude            DOUBLE PRECISION            NOT NULL,
    longitude           DOUBLE PRECISION            NOT NULL,
    max_distance_km     INTEGER                     NOT NULL,
    min_age             INTEGER                     NOT NULL,
    max_age             INTEGER                     NOT NULL,
    preferred_gender    VARCHAR(20),
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_active         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_age_range CHECK (min_age <= max_age)
);

-- Bounding-box prefilter for potential matches.
CREATE INDEX idx_users_location ON users (latitude, longitude);

CREATE TABLE user_interests (
    user_id  BIGINT      NOT NULL,
    interest VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, interest),
    CONSTRAINT fk_user_interests_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE swipes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    swiper_id  BIGINT                      NOT NULL,
    swiped_id  BIGINT                      NOT NULL,
    liked      BOOLEAN                     NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_swipes_pair UNIQUE (swiper_id, swiped_id),
    CONSTRAINT ck_swipes_not_self CHECK (swiper_id <> swiped_id),
    CONSTRAINT fk_swipes_swiper FOREIGN KEY (swiper_id) REFERENCES users (id),
    CONSTRAINT fk_swipes_swiped FOREIGN KEY (swiped_id) REFERENCES users (id)
);

-- Reverse lookup for "did they already like me?".
CREATE INDEX idx_swipes_reverse ON swipes (swiped_id, swiper_id, liked);

CREATE TABLE matches (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user1_id   BIGINT                      NOT NULL,
    user2_id   BIGINT                      NOT NULL,
    matched_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    active     BOOLEAN                     NOT NULL,
    CONSTRAINT uk_matches_pair UNIQUE (user1_id, user2_id),
    -- Canonical ordering so (A,B) and (B,A) can't both exist.
    CONSTRAINT ck_matches_ordered CHECK (user1_id < user2_id),
    CONSTRAINT fk_matches_user1 FOREIGN KEY (user1_id) REFERENCES users (id),
    CONSTRAINT fk_matches_user2 FOREIGN KEY (user2_id) REFERENCES users (id)
);

-- user1_id is covered by the unique constraint's index.
CREATE INDEX idx_matches_user2 ON matches (user2_id);

CREATE TABLE chat_messages (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id  BIGINT                      NOT NULL,
    sender_id BIGINT                      NOT NULL,
    content   VARCHAR(2000)               NOT NULL,
    sent_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    is_read   BOOLEAN                     NOT NULL,
    CONSTRAINT fk_chat_messages_match FOREIGN KEY (match_id) REFERENCES matches (id),
    CONSTRAINT fk_chat_messages_sender FOREIGN KEY (sender_id) REFERENCES users (id)
);

-- Conversation paging (newest first by id) and unread lookups.
CREATE INDEX idx_chat_messages_match ON chat_messages (match_id, id);
CREATE INDEX idx_chat_messages_unread ON chat_messages (match_id, is_read);
